const brief = read()
const dirs = fs.readdirSync(path.join(ROOT, 'design/directions')).filter((d) => fs.existsSync(path.join(ROOT, 'design/directions', d, 'direction.json')))
if (!dirs.includes(brief.direction)) {
  console.error(`Unknown direction "${brief.direction}". Available: ${dirs.join(', ')}`)
  process.exit(1)
}
console.log(`Scaffolding ${brief.org.name} (${brief.slug}) · direction ${brief.direction} · pages ${brief.pages.join(', ')}`)
write('design/active.ts', activeTs(brief), { protect: true })
write('lib/collections.ts', collectionsTs(brief), { protect: true })
const direction = JSON.parse(fs.readFileSync(path.join(ROOT, 'design/directions', brief.direction, 'direction.json'), 'utf8')) as DirectionMeta
for (const key of brief.pages) write(key === 'home' ? 'app/(site)/page.tsx' : `app/(site)/${key}/page.tsx`, pageFile(brief, key, direction), { protect: false })
write('app/(site)/privacy/page.tsx', privacyPage(brief), { protect: true })
write('app/(site)/[slug]/page.tsx', pagePage, { protect: true })
if (brief.features.posts) write('app/(site)/posts/[slug]/page.tsx', postPage, { protect: true })
else fs.rmSync(path.join(ROOT, 'app/(site)/posts/[slug]'), { recursive: true, force: true })
if (brief.features.events) write('app/(site)/events/[slug]/page.tsx', eventPage, { protect: true })
else fs.rmSync(path.join(ROOT, 'app/(site)/events/[slug]'), { recursive: true, force: true })
// Pages the brief no longer asks for are removed so the sitemap and nav stay truthful.
let removed = false
for (const key of ['about', 'events', 'posts', 'gallery', 'donate', 'contact', 'volunteer'] as PageKey[]) {
  if (!brief.pages.includes(key) && fs.existsSync(path.join(ROOT, 'app/(site)', key, 'page.tsx'))) {
    fs.rmSync(path.join(ROOT, 'app/(site)', key, 'page.tsx'))
    console.log(`  remove   app/(site)/${key}/page.tsx`)
    removed = true
  }
}
// Next's generated route validator references pages that no longer exist; drop it so typecheck is truthful.
if (removed || !brief.features.posts || !brief.features.events) fs.rmSync(path.join(ROOT, '.next/types'), { recursive: true, force: true })
console.log('done')
